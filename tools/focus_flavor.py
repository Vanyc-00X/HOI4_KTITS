def target_sizes(big: bool) -> dict:
    return dict(SIZES_BIG if big else SIZES_SMALL)


def _pick(pool: list[str], tag: str, sec: str, i: int) -> str:
    h = sum(ord(c) for c in tag + sec) + i * 17
    return pool[h % len(pool)]


def expand_spec(tag: str, spec: dict) -> dict:
    """Return a copied country spec padded with shared and country-specific foci."""
    import copy

    s = copy.deepcopy(spec)
    sizes = target_sizes(s["big"])
    for sec, n in sizes.items():
        if sec == "absurd":
            names = list(ABSURD_BRANCHES[tag])
            for i in range(n - len(names)):
                names.append(ABSURD_MORE[i])
            s[sec] = {"desc": ABSURD_DESCRIPTIONS[tag], "names": names}
            continue
        names = list(s[sec]["names"])
        if sec == "start":
            pool = START_EXTRA + START_MORE
        elif sec == "eco":
            pool = ECO_EXTRA + ECO_MORE
        elif sec == "army":
            pool = ARMY_EXTRA + ARMY_MORE
        elif sec == "diplo":
            pool = DIPLO_EXTRA + DIPLO_MORE
        elif sec == "secret":
            pool = SECRET_EXTRA + SECRET_MORE
        else:
            pool = BRANCH_EXTRA[s[sec]["ideology"]] + BRANCH_MORE[s[sec]["ideology"]]
        used = set(names)
        k = 0
        while len(names) < n:
            cand = _pick(pool, tag, sec, k)
            label = cand if cand not in used else f"{cand} ({tag})"
            if label in used:
                label = f"{cand} #{k + 1}"
            names.append(label)
            used.add(label)
            k += 1
        for index, label in SPECIAL_FOCUS_NAMES.get(tag, {}).get(sec, {}).items():
            if index < n:
                names[index] = label
        s[sec]["names"] = names
    return s
