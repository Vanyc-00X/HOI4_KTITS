def patch_on_actions() -> None:
    path = ROOT / "common" / "on_actions" / "mk_on_actions.txt"
    text = path.read_text(encoding="utf-8")
    begin = "\t# BEGIN generated ruler-capture actions"
    end = "\t# END generated ruler-capture actions"
    if begin in text and end in text:
        left = text.index(begin)
        right = text.index(end, left) + len(end)
        text = text[:left] + text[right:]
    closing = text.rfind("}")
    if closing < 0:
        raise SystemExit(f"Could not find on_actions root close in {path}")
    text = text[:closing].rstrip() + "\n\n" + render_capture_actions() + "\n" + text[closing:]
    path.write_text(text, encoding="utf-8")


