def cosmetic_tag(tag: str, ideology: str) -> str:
    """Cosmetic tag id used in set_cosmetic_tag / flags / loc."""
    return f"{tag}_{ideology}"


def blend_rgb(tag: str, ideology: str) -> tuple[int, int, int]:
    base = TAG_RGB[tag]
    tint = IDEOLOGY_TINT[ideology]
    return tuple(max(0, min(255, (b * 2 + t) // 3)) for b, t in zip(base, tint))
