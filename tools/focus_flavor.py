def target_sizes(big: bool) -> dict:
    return dict(SIZES_BIG if big else SIZES_SMALL)


def _pick(pool: list[str], tag: str, sec: str, i: int) -> str:
    h = sum(ord(c) for c in tag + sec) + i * 17
    return pool[h % len(pool)]


def expand_spec(tag: str, spec: dict) -> dict:
    """Return a copied country spec padded with shared and country-specific foci."""
    import copy

    s = copy.deepcopy(spec)
    sizes = target_sizes(s["big"])
    for sec, n in sizes.items():
        if sec == "absurd":
            s[sec] = {
                "desc": ABSURD_DESCRIPTIONS[tag],
                "names": list(ABSURD_BRANCHES[tag]),
            }
            continue
        names = list(s[sec]["names"])
        if sec == "start":
            pool = START_EXTRA
        elif sec == "eco":
            pool = ECO_EXTRA
        elif sec == "army":
            pool = ARMY_EXTRA
        elif sec == "diplo":
            pool = DIPLO_EXTRA
        elif sec == "secret":
            pool = SECRET_EXTRA
        else:
            pool = BRANCH_EXTRA[s[sec]["ideology"]]
        used = set(names)
        k = 0
        while len(names) < n:
            cand = _pick(pool, tag, sec, k)
            label = cand if cand not in used else f"{cand} ({tag})"
            if label in used:
                label = f"{cand} #{k + 1}"
            names.append(label)
            used.add(label)
            k += 1
        s[sec]["names"] = names
    return s
