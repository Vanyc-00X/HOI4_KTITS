def render_traits() -> str:
    lines = [
        "# Generated by tools/build_ruler_content.py. Ruler bonuses shift with the governing ideology.",
        "leader_traits = {",
    ]
    for tag in TAGS:
        ruler = RULERS[tag]
        for ideology in (None, *IDEOLOGIES):
            current_trait = trait_id(tag, ideology)
            lines += [f"\t{current_trait} = {{", "\t\trandom = no", "\t\tsprite = 1"]
            mods = ruler["mods"] if ideology is None else ruler_trait_mods(tag, ideology)
            for modifier, value in mods.items():
                lines.append(f"\t\t{modifier} = {value:g}")
            lines += ["\t\tai_will_do = { factor = 0 }", "\t}"]
    lines.append("}")
    return "\n".join(lines) + "\n"


def attach_leader_traits(tag: str) -> None:
    path = ROOT / "common" / "characters" / f"{tag}.txt"
    lines = path.read_text(encoding="utf-8").splitlines()
    i = 0
    count = 0
    while i < len(lines):
        if lines[i].strip() != "country_leader = {":
            i += 1
            continue
        start = i
        depth = 1
        j = i + 1
        while j < len(lines) and depth:
            depth += lines[j].count("{") - lines[j].count("}")
            j += 1
        if depth:
            raise SystemExit(f"Unclosed country_leader block in {path}")
        close = j - 1
        body = lines[start + 1:close]
        ideology_line = next(
            (line.strip().split("=", 1)[1].strip() for line in body
             if line.strip().startswith("ideology =")),
            None,
        )
        if not ideology_line:
            raise SystemExit(f"Missing ideology in country_leader block in {path}")
        current_trait = trait_id(tag, map_ideology(ideology_line))
        traits_index = next(
            (start + 1 + offset for offset, line in enumerate(body)
             if line.strip().startswith("traits =")),
            None,
        )
        if traits_index is None:
            indent = lines[start][:len(lines[start]) - len(lines[start].lstrip())] + "\t"
            lines.insert(close, f"{indent}traits = {{ {current_trait} }}")
            close += 1
        else:
            traits_line = lines[traits_index]
            traits_match = re.search(r"traits\s*=\s*\{([^}]*)\}", traits_line)
            if not traits_match:
                raise SystemExit(f"Unsupported traits block in {path}: {traits_line.strip()}")
            traits = [
                token for token in traits_match.group(1).split()
                if not token.startswith("mk_ruler_")
            ]
            traits.append(current_trait)
            lines[traits_index] = re.sub(
                r"traits\s*=\s*\{[^}]*\}",
                "traits = { " + " ".join(traits) + " }",
                traits_line,
                count=1,
            )
        count += 1
        i = close + 1
    if count != 4:
        raise SystemExit(f"Expected four country_leader roles in {path}, found {count}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


